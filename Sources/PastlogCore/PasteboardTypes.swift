import Foundation

public enum PasteboardTypes {
    public static let plainText = "public.utf8-plain-text"
    public static let fileURL = "public.file-url"
    public static let url = "public.url"
    public static let color = "com.apple.cocoa.pasteboard.color"

    public static let imageTypes: Set<String> = [
        "public.png", "public.tiff", "public.jpeg", "public.heic", "public.heif",
        "com.compuserve.gif", "org.webmproject.webp", "com.adobe.pdf", "public.image",
        "com.apple.pict",
    ]

    public static let richTextTypes: Set<String> = [
        "public.rtf", "public.html", "com.apple.flat-rtfd", "com.apple.rtfd",
        "com.apple.webarchive", "Apple Web Archive pasteboard type",
    ]

    /// Markers from the nspasteboard.org convention used by password managers and
    /// utilities to flag secrets or throwaway content that clipboard managers should skip.
    public static let sensitiveMarkers: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
        "net.antelle.keeweb",
    ]

    /// Types kept when a clip exceeds the size cap.
    public static let essential: Set<String> = [
        plainText, fileURL, url, "public.png", "public.jpeg", "public.rtf",
    ]

    public static func isSensitive(types: Set<String>) -> Bool {
        !types.isDisjoint(with: sensitiveMarkers)
    }

    public static func looksLikeLink(_ text: String) -> Bool {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty, !trimmed.contains(where: \.isWhitespace),
              let url = URL(string: trimmed), let scheme = url.scheme?.lowercased() else { return false }
        if ["http", "https", "ftp"].contains(scheme) { return url.host != nil }
        return ["mailto", "tel", "sms", "facetime", "slack", "zoommtg", "vscode", "x-github-client"].contains(scheme)
    }

    public static func classify(types: Set<String>, plainText: String?) -> ClipKind {
        if types.contains(fileURL) { return .file }
        if !types.isDisjoint(with: imageTypes) { return .image }
        if types.contains(color) { return .color }
        if let plainText, !plainText.isEmpty {
            if looksLikeLink(plainText) { return .link }
            if !types.isDisjoint(with: richTextTypes) { return .richText }
            return .text
        }
        if types.contains(url) { return .link }
        if !types.isDisjoint(with: richTextTypes) { return .richText }
        return .other
    }

    public static func title(kind: ClipKind, plainText: String?, filePaths: [String],
                             imageWidth: Int?, imageHeight: Int?, types: Set<String>) -> String {
        switch kind {
        case .file:
            let names = filePaths.map { ($0 as NSString).lastPathComponent }
            if names.count > 3 { return names.prefix(3).joined(separator: ", ") + " +\(names.count - 3) more" }
            return names.joined(separator: ", ")
        case .image:
            if let w = imageWidth, let h = imageHeight { return "Image \(w) × \(h)" }
            return "Image"
        default:
            if let text = plainText {
                let collapsed = text.split(whereSeparator: \.isNewline)
                    .map { $0.trimmingCharacters(in: .whitespaces) }
                    .first(where: { !$0.isEmpty }) ?? text.trimmingCharacters(in: .whitespacesAndNewlines)
                return String(collapsed.prefix(300))
            }
            if kind == .color { return "Color" }
            return types.sorted().first ?? "Clipboard item"
        }
    }
}
